/** Sözlüğün tipi: fonksiyon imzaları korunur, metin değerleri herhangi bir metin olabilir */
export type Widen<T> = T extends (...args: infer A) => infer R
  ? (...args: A) => R
  : T extends string
    ? string
    : T extends readonly (infer E)[]
      ? Widen<E>[]
      : { [K in keyof T]: Widen<T[K]> }

export type Dict = Widen<typeof tr>
