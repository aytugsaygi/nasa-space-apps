import { AnimatePresence, motion, useReducedMotion, type Variants } from 'motion/react'
import { ListChecks, Move3d, Target } from 'lucide-react'
import { lazy, Suspense, useEffect, useLayoutEffect, useMemo, useRef, useState } from 'react'
import { EXERCISES } from '../core/coach'
import { CREW } from '../core/crew'
import { useHealth } from '../data/health'
import { resolve, useI18n } from '../i18n'
import { resetTrainer, setTrainer, useTrainer } from './trainerStore'

const TrainerScene = lazy(() => import('./TrainerScene'))

function hasWebGL() {
  try {
    const c = document.createElement('canvas')
    return !!(c.getContext('webgl2') || c.getContext('webgl'))
  } catch {
    return false
  }
}

/**
 * Hologram antrenör: programdan seçilen hareketi 3D hologram yapar. Sürükleyerek açı değiştirilir (doğru formu her
 * açıdan görmek için); çalışan bölgeler parlar, yanında formun püf noktaları yazar.
 */
export function TrainerStage({ active, reducedMotion }: { active: boolean; reducedMotion: boolean }) {
  const { t, lang } = useI18n()
  const { exercise, playing, view } = useTrainer()
  const { astronaut } = useHealth()
  const body = astronaut ? CREW[astronaut].sex : 'm'
  const webgl = useMemo(hasWebGL, [])
  const ex = exercise ? EXERCISES[exercise] : null
  const name = ex ? resolve(ex.name, lang) : t.sport.trainerTitle
  const reduce = useReducedMotion() ?? false
  const v = useMemo(() => variants(reduce), [reduce])
  // Alt bilgi alanının gerçek yüksekliği ölçülür ve bu yüksekliğe yumuşakça gidilir: üstteki hologram alanı da aynı
  // hızla küçülür ya da büyür (yalnızca dönüşümle canlandırılınca hologram alanı bir anda boyut değiştiriyordu)
  const info = useRef<HTMLDivElement>(null)
  const [infoH, setInfoH] = useState<number | 'auto'>('auto')
  useLayoutEffect(() => {
    const el = info.current
    if (!el) return
    const ro = new ResizeObserver(() => setInfoH(el.offsetHeight))
    ro.observe(el)
    return () => ro.disconnect()
  }, [])

  // Başka sayfaya geçince hareket bırakılır ve hologram ilk görünümüne döner (dönünce normal görünüm karşılar)
  const wasActive = useRef(active)
  useEffect(() => {
    if (wasActive.current && !active) resetTrainer()
    wasActive.current = active
  }, [active])
  useEffect(() => {
    const onVisibility = () => document.hidden && setTrainer({ playing: false })
    document.addEventListener('visibilitychange', onVisibility)
    return () => document.removeEventListener('visibilitychange', onVisibility)
  }, [])

  return (
    <section id="tour-trainer" aria-label={t.sport.trainerTitle} className="panel relative flex size-full min-h-0 flex-col overflow-hidden !rounded-3xl">
      <header className="pointer-events-none absolute inset-x-0 top-0 z-10 flex items-start justify-between gap-3 p-5">
        <div className="min-w-0">
          <p className="font-mono font-semibold text-[13.5px] tracking-[0.07em] text-ink-dim uppercase">{t.sport.trainerTitle}</p>
          <h2 className="mt-1 font-display text-[20px] leading-tight font-semibold">{name}</h2>
          {ex && <p className="mt-0.5 text-[14.5px] text-ink-muted">{t.sport.device[ex.device]}</p>}
        </div>
      </header>

      {/* Arkada spor salonu görseli (Gemini ile üretildi, sol altta "GENERATED BY GEMINI" filigranı; SI listelerinde).
          3D tuval saydam olduğu için görsel hologramın arkasında kalır; sol alta yaslı kırpılır, filigran kesilmez. */}
      <div className="relative min-h-0 flex-1 bg-[url('/textures/hologram-gym.png')] bg-cover bg-left-bottom">
        {webgl ? (
          <Suspense
            fallback={
              <div className="flex h-full items-center justify-center text-ink-dim" role="status">
                <span className="font-mono font-semibold text-[13.5px] tracking-[0.07em] uppercase">{t.sport.loading}</span>
              </div>
            }
          >
            <TrainerScene key={view} body={body} exercise={exercise} playing={playing} active={active} reducedMotion={reducedMotion} label={t.sport.canvasLabel(name)} />
          </Suspense>
        ) : (
          <p className="p-6 pt-24 text-[15.5px] text-ink-muted">{t.sport.noWebgl}</p>
        )}
        <p className="pointer-events-none absolute bottom-3 left-4 flex items-center gap-1.5 rounded-full bg-black/40 px-3 py-1 text-[13.5px] text-ink-dim backdrop-blur">
          <Move3d size={13} aria-hidden />
          {t.sport.dragHint}
        </p>
      </div>

      {/*
        Altta iki sütun: solda doğru form, sağda hareketin ne işe yaradığı (dar ekranda alt alta). Hareket değişince alan
        yumuşakça büyür ya da küçülür; bölümler sırayla, maddeler tek tek kayarak gelir (hareket azaltılmışsa yalnızca solar).
      */}
      <motion.div
        initial={false}
        animate={{ height: infoH }}
        transition={{ duration: reduce ? 0 : 0.5, ease: [0.22, 1, 0.36, 1] }}
        className="shrink-0 overflow-hidden border-t border-holo/20 bg-black/35"
      >
        <div ref={info} className="@container px-5 py-3.5">
          <AnimatePresence mode="wait" initial={false}>
            {ex ? (
              <motion.div key={exercise} data-trainer-info variants={v.box} initial="hidden" animate="show" exit="exit" className="grid gap-x-6 gap-y-3 @min-[28rem]:grid-cols-2">
                <motion.section variants={v.part} aria-labelledby="trainer-form">
                  <h3 id="trainer-form" className="flex items-center gap-1.5 font-mono text-[13.5px] font-semibold tracking-[0.07em] text-holo uppercase">
                    <ListChecks size={15} aria-hidden />
                    {t.sport.form}
                  </h3>
                  <motion.ul variants={v.list} className="mt-1.5 space-y-1 text-[15px] leading-snug text-ink">
                    {ex.cues.map((c) => (
                      <motion.li key={c.tr} variants={v.item} className="flex gap-2">
                        <span className="mt-[7px] size-1.5 shrink-0 rounded-full bg-holo shadow-[0_0_6px_var(--color-holo)]" aria-hidden />
                        {resolve(c, lang)}
                      </motion.li>
                    ))}
                  </motion.ul>
                </motion.section>
                <motion.section variants={v.part} aria-labelledby="trainer-purpose" className="@min-[28rem]:border-l @min-[28rem]:border-line @min-[28rem]:pl-6">
                  <h3 id="trainer-purpose" className="flex items-center gap-1.5 font-mono text-[13.5px] font-semibold tracking-[0.07em] text-holo uppercase">
                    <Target size={15} aria-hidden />
                    {t.sport.purpose}
                  </h3>
                  <motion.p variants={v.item} className="mt-1.5 text-[15px] leading-snug text-ink">
                    {resolve(ex.about, lang)}
                  </motion.p>
                </motion.section>
              </motion.div>
            ) : (
              <motion.p key="idle" variants={v.box} initial="hidden" animate="show" exit="exit" className="text-[15px] text-ink-muted">
                {t.sport.idle}
              </motion.p>
            )}
          </AnimatePresence>
        </div>
      </motion.div>
    </section>
  )
}

/** Alt bilgi alanının giriş ve çıkış hareketleri; hareket azaltılmışsa yalnızca saydamlık değişir */
function variants(reduce: boolean): Record<'box' | 'part' | 'list' | 'item', Variants> {
  const ease = [0.22, 1, 0.36, 1] as const
  if (reduce) {
    const fade: Variants = { hidden: { opacity: 0 }, show: { opacity: 1, transition: { duration: 0.15 } }, exit: { opacity: 0, transition: { duration: 0.1 } } }
    return { box: fade, part: {}, list: {}, item: {} }
  }
  return {
    box: {
      hidden: { opacity: 0 },
      show: { opacity: 1, transition: { duration: 0.2, staggerChildren: 0.12 } },
      exit: { opacity: 0, y: -6, transition: { duration: 0.16, ease: 'easeIn' } },
    },
    part: {
      hidden: { opacity: 0, y: 12, filter: 'blur(4px)' },
      show: { opacity: 1, y: 0, filter: 'blur(0px)', transition: { duration: 0.4, ease, staggerChildren: 0.07, delayChildren: 0.1 } },
    },
    list: { hidden: {}, show: { transition: { staggerChildren: 0.07 } } },
    item: {
      hidden: { opacity: 0, x: -10 },
      show: { opacity: 1, x: 0, transition: { duration: 0.32, ease } },
    },
  }
}
